#!/usr/bin/env node
// Mirrors the kit's skills and rules into the open `.agents/` tree read by hosts other than Claude Code
// and Cursor (verified against each host's docs, 2026-10-29):
//   .agents/skills/<name>/SKILL.md — Codex (repo + parents), Antigravity, Copilot CLI / coding agent
//   .agents/rules/<name>.md        — Antigravity only (needs a `trigger` frontmatter or it drops the rule)
// AGENTS.md (generate-mirrors.js) already carries the always-on NEVER/ALWAYS for all of them.
// Sources stay `.claude/skills` and `.cursor/rules`; never edit `.agents/` by hand. Two files here are not
// ours and carry no marker: `.agents/skills/studio` (sync-director-prompt.js) and `.agents/rules/motion-studio.md`.
// Usage: node .ai/scripts/sync-agent-hosts.js [targetDir] [--check]
const fs = require('fs');
const path = require('path');

const args = process.argv.slice(2);
const CHECK = args.includes('--check');
const ROOT = path.resolve(args.find((a) => !a.startsWith('--')) || process.cwd());
const MARKER = '<!-- generated by .ai/scripts/sync-agent-hosts.js';

// Claude-only: they drive Agent()/agent teams, Playwright MCP or the kit's own Claude/Cursor files.
// `studio` is copied byte for byte by sync-director-prompt.js, with its Director rules blocks.
const SKILL_EXCLUDE = new Set(['agent-teams-workflow', 'qa-test', 'update-propagation', 'studio']);
// Cursor model/cost strategy and Cursor's agent-driven workflow — meaningless on another host.
const RULE_EXCLUDE = new Set(['token-optimization', 'workflow', 'workflow-tdd']);
// Mirrored skill bodies still name Claude agents, slash commands and .claude/scripts.
const HOST_NOTE = '> Host note: this skill is mirrored from the Claude Code kit. Steps that name Claude agents (`explore`, `senior-dev`, `tech-lead`, `qa`), slash commands (`/workflow`, `/loop-ticket`, `/epic`) or `.claude/scripts/*` describe that host\'s orchestration — apply the rules and checklists directly and skip those steps.\n\n';
const SECRET_FILE = /(^|[\\/])(\.env(\.[\w-]+)?|CLAUDE\.local\.md|[\w.-]+\.local\.json|accounts\.json|\.mcp\.json|credentials(\.[\w-]+)?|secrets\.json|[\w.-]+\.(pem|key|pfx|p12))$/i;
// Codex lists skills within ~2% of context, 8,000 chars when the window is unknown.
const CODEX_LIST_BUDGET = 8000;

function splitFrontmatter(text) {
  const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/);
  if (!m) return { fm: {}, body: text };
  const fm = {};
  const lines = m[1].split(/\r?\n/);
  for (let i = 0; i < lines.length; i++) {
    const kv = lines[i].match(/^([A-Za-z][\w-]*):\s*(.*)$/);
    if (!kv) continue;
    let value = kv[2].trim();
    // YAML block scalar (`description: >` / `|`): the value is the indented lines that follow.
    if (/^[>|][-+]?$/.test(value)) {
      const parts = [];
      while (i + 1 < lines.length && /^\s+\S/.test(lines[i + 1])) parts.push(lines[++i].trim());
      value = parts.join(' ');
    }
    fm[kv[1]] = value.replace(/^"(.*)"$/, '$1').replace(/\\"/g, '"');
  }
  return { fm, body: text.slice(m[0].length) };
}

const q = (s) => JSON.stringify(s);

function skillOutputs() {
  const src = path.join(ROOT, '.claude', 'skills');
  const out = new Map();
  if (!fs.existsSync(src)) return out;
  for (const name of fs.readdirSync(src).sort()) {
    const dir = path.join(src, name);
    const skillFile = path.join(dir, 'SKILL.md');
    if (SKILL_EXCLUDE.has(name) || !fs.existsSync(skillFile)) continue;
    const { fm, body } = splitFrontmatter(fs.readFileSync(skillFile, 'utf8'));
    if (!fm.description) continue;
    // Spec minimum only: allowed-tools, context, agent, paths, argument-hint are Claude-only keys.
    const head = `---\nname: ${q(fm.name || name)}\ndescription: ${q(fm.description)}\n---\n`;
    out.set(`.agents/skills/${name}/SKILL.md`, `${head}${MARKER} from .claude/skills/${name}/SKILL.md — edit the source -->\n${HOST_NOTE}${body}`);
    for (const extra of walk(dir)) {
      const rel = path.relative(dir, extra).split(path.sep).join('/');
      if (rel !== 'SKILL.md') out.set(`.agents/skills/${name}/${rel}`, fs.readFileSync(extra));
    }
  }
  return out;
}

function ruleOutputs() {
  const src = path.join(ROOT, '.cursor', 'rules');
  const out = new Map();
  if (!fs.existsSync(src)) return out;
  for (const file of fs.readdirSync(src).filter((f) => f.endsWith('.mdc')).sort()) {
    const name = file.slice(0, -4);
    if (RULE_EXCLUDE.has(name)) continue;
    const { fm, body } = splitFrontmatter(fs.readFileSync(path.join(src, file), 'utf8'));
    const lines = [];
    if (fm.alwaysApply === 'true') lines.push('trigger: always_on');
    else if (fm.globs) lines.push('trigger: glob', `globs: ${q(fm.globs)}`);
    else if (fm.description) lines.push('trigger: model_decision');
    else lines.push('trigger: manual');
    if (fm.description) lines.push(`description: ${q(fm.description)}`);
    out.set(`.agents/rules/${name}.md`, `---\n${lines.join('\n')}\n---\n${MARKER} from .cursor/rules/${file} — edit the source -->\n${body}`);
  }
  return out;
}

// Regular files only: a symlink/junction is skipped (it could point outside the repo), and so is
// anything shaped like a secret, since .agents/ ships in the export package.
function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name);
    if (e.isSymbolicLink()) return [];
    if (e.isDirectory()) return walk(p);
    return e.isFile() && !SECRET_FILE.test(p) ? [p] : [];
  });
}

// Only files under a folder whose SKILL.md / rule carries the marker are ours to remove.
function staleGenerated(expected) {
  const stale = [];
  const skillsDir = path.join(ROOT, '.agents', 'skills');
  if (fs.existsSync(skillsDir)) {
    for (const name of fs.readdirSync(skillsDir)) {
      const skill = path.join(skillsDir, name, 'SKILL.md');
      if (!fs.existsSync(skill) || !fs.readFileSync(skill, 'utf8').includes(MARKER)) continue;
      for (const f of walk(path.join(skillsDir, name))) {
        const rel = path.relative(ROOT, f).split(path.sep).join('/');
        if (!expected.has(rel)) stale.push(rel);
      }
    }
  }
  const rulesDir = path.join(ROOT, '.agents', 'rules');
  if (fs.existsSync(rulesDir)) {
    for (const e of fs.readdirSync(rulesDir, { withFileTypes: true })) {
      if (!e.isFile()) continue;
      const rel = `.agents/rules/${e.name}`;
      if (!expected.has(rel) && fs.readFileSync(path.join(ROOT, rel), 'utf8').includes(MARKER)) stale.push(rel);
    }
  }
  return stale;
}

const expected = new Map([...skillOutputs(), ...ruleOutputs()]);
const changed = [...expected].filter(([rel, content]) => {
  const p = path.join(ROOT, rel);
  return !fs.existsSync(p) || !fs.readFileSync(p).equals(Buffer.from(content));
}).map(([rel]) => rel);
const stale = staleGenerated(expected);

const listChars = [...expected]
  .filter(([rel]) => rel.endsWith('/SKILL.md'))
  .reduce((n, [, c]) => n + splitFrontmatter(String(c)).fm.description.length, 0);
if (listChars > CODEX_LIST_BUDGET) {
  console.log(`⚠ skill descriptions total ${listChars} chars — over Codex's ${CODEX_LIST_BUDGET}-char default list budget`);
}

if (CHECK) {
  if (!changed.length && !stale.length) {
    console.log(`✓ .agents/ in sync (${expected.size} files)`);
    process.exit(0);
  }
  for (const rel of changed) console.log(`✗ out of date: ${rel}`);
  for (const rel of stale) console.log(`✗ stale: ${rel}`);
  console.log('Run: node .ai/scripts/sync-agent-hosts.js');
  process.exit(1);
}

for (const rel of changed) {
  const p = path.join(ROOT, rel);
  fs.mkdirSync(path.dirname(p), { recursive: true });
  fs.writeFileSync(p, expected.get(rel));
}
for (const rel of stale) {
  fs.unlinkSync(path.join(ROOT, rel));
  for (let d = path.dirname(path.join(ROOT, rel)); d.startsWith(path.join(ROOT, '.agents')) && !fs.readdirSync(d).length; d = path.dirname(d)) {
    fs.rmdirSync(d);
  }
}
const keys = [...expected.keys()];
const skills = keys.filter((r) => r.endsWith('/SKILL.md')).length;
const rules = keys.filter((r) => r.startsWith('.agents/rules/')).length;
console.log(`✓ .agents/ synced: ${skills} skills, ${rules} rules — ${changed.length} written, ${stale.length} removed (description list ${listChars} chars)`);
