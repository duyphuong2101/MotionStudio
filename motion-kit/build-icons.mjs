// Dev-only: turns the icons named in icon-list.json into motion-kit paths in icons-set.mjs.
// Get the source once: `npm pack @phosphor-icons/core` in a temp folder, extract it, then
//   node motion-kit/build-icons.mjs <extracted package folder>
// Nothing here runs at render time and no package is added to the project.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { StudioError, readJson, within, assertFileName } from '../engine/core.mjs';
import { svgToIconPath, ICON_NAME_RE, ICON_PATH_RE, MAX_PATH_CHARS } from '../engine/icons.mjs';
import { BASE_ICONS } from './icons.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));

/** The list as [name, source icon, group] rows, checked for clean and unique names. */
export function iconRows(list) {
  const rows = Object.entries(list.groups || {}).flatMap(([group, icons]) => Object.entries(icons).map(([name, src]) => [name, src, group]));
  const seen = new Set();
  for (const [name, src] of rows) {
    if (!ICON_NAME_RE.test(name)) throw new StudioError(`Icon name "${name}" must start with a letter and use a-z, 0-9 and dashes`, 400);
    if (BASE_ICONS[name] || seen.has(name)) throw new StudioError(`Icon name "${name}" is used twice`, 400);
    assertFileName(`${src}-${list.weight}.svg`, 'icon source');
    seen.add(name);
  }
  return rows;
}

export function buildIconSet(pkgDir, list = readJson(path.join(HERE, 'icon-list.json'))) {
  const pkg = readJson(within(pkgDir, 'package.json'));
  if (pkg.name !== list.source) throw new StudioError(`Expected ${list.source}, found ${pkg.name || 'no package'} in ${pkgDir}`, 400);
  const lines = [];
  let group = '';
  for (const [name, src, g] of iconRows(list)) {
    const file = `${src}-${list.weight}.svg`;
    const d = svgToIconPath(fs.readFileSync(within(pkgDir, 'assets', list.weight, file), 'utf8'), file);
    if (!ICON_PATH_RE.test(d) || d.length > MAX_PATH_CHARS) throw new StudioError(`${file} gave a path the motion kit cannot store`, 400);
    if (g !== group) lines.push(`  // ${(group = g)}`);
    lines.push(`  ${/-/.test(name) ? `'${name}'` : name}: '${d}',`);
  }
  return `// Generated by motion-kit/build-icons.mjs from ${pkg.name} ${pkg.version} (${list.weight}, MIT: see LICENSE-phosphor.txt). Do not edit.
export const SET_ICONS = {
${lines.join('\n')}
};
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const dir = process.argv[2];
  if (!dir) {
    console.error('Usage: node motion-kit/build-icons.mjs <extracted @phosphor-icons/core folder>');
    process.exit(1);
  }
  try {
    const text = buildIconSet(path.resolve(dir));
    fs.writeFileSync(path.join(HERE, 'icons-set.mjs'), text, 'utf8');
    console.log(`${(text.match(/^ {2}[^/ ]/gm) || []).length} icons written to motion-kit/icons-set.mjs`);
  } catch (err) {
    console.error(err.message);
    process.exit(1);
  }
}
